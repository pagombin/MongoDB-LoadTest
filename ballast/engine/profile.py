"""Workload profiles: what to send, how fast, and with which driver settings."""

from __future__ import annotations

import re
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from mongo_load_tester.config import SchemaFieldConfig

NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 ._-]{0,79}$")
DB_NAME_RE = re.compile(r"^[A-Za-z0-9_-]{1,63}$")
COLL_PREFIX_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]{0,40}$")
SYSTEM_DATABASES = {"admin", "local", "config"}


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class OperationMix(Strict):
    find: float = Field(default=60, ge=0)
    range: float = Field(default=0, ge=0)
    insert: float = Field(default=10, ge=0)
    update: float = Field(default=30, ge=0)
    upsert: float = Field(default=0, ge=0)
    delete: float = Field(default=0, ge=0)
    aggregate: float = Field(default=0, ge=0)
    find_and_modify: float = Field(default=0, ge=0)
    analytics: float = Field(default=0, ge=0, description="Aggregation that scans keys.analytics_docs documents and groups them.")

    @model_validator(mode="after")
    def _positive(self) -> OperationMix:
        if sum(self.weights().values()) <= 0:
            raise ValueError("at least one operation needs a weight above 0")
        return self

    def weights(self) -> dict[str, float]:
        return {k: float(v) for k, v in self.model_dump().items()}

    def normalized(self) -> dict[str, float]:
        weights = self.weights()
        total = sum(weights.values())
        return {k: v / total for k, v in weights.items() if v > 0}

    def has_writes(self) -> bool:
        w = self.weights()
        return any(w[k] > 0 for k in ("insert", "update", "upsert", "delete", "find_and_modify"))


class DocumentSpec(Strict):
    mode: Literal["simple", "schema"] = "simple"
    size_bytes: int = Field(default=512, ge=64, le=4 * 1024 * 1024)
    fields: int = Field(default=8, ge=1, le=200)
    schema_fields: list[SchemaFieldConfig] | None = Field(
        default=None, description="Field definitions used when mode is 'schema' (same format as the legacy schema)."
    )

    @model_validator(mode="after")
    def _schema(self) -> DocumentSpec:
        if self.mode == "schema" and not self.schema_fields:
            raise ValueError("schema_fields is required when mode is 'schema'")
        if self.schema_fields:
            names = [f.name for f in self.schema_fields]
            if "_id" in names:
                raise ValueError("_id is generated by Ballast and cannot be a schema field")
            if len(names) != len(set(names)):
                raise ValueError("schema field names must be unique")
        return self


class KeySpec(Strict):
    distribution: Literal["uniform", "zipfian", "sequential"] = "uniform"
    zipf_theta: float = Field(default=0.99, gt=0, lt=5)
    range_size: int = Field(default=20, ge=1, le=10_000)
    analytics_docs: int = Field(default=5_000, ge=1, le=10_000_000, description="Documents scanned by each analytics query.")


class IndexSpec(Strict):
    keys: dict[str, Literal[1, -1, "hashed"]]
    unique: bool = False

    @field_validator("keys")
    @classmethod
    def _keys(cls, value: dict) -> dict:
        if not value:
            raise ValueError("an index needs at least one key")
        return value


class DataLoad(Strict):
    documents: int = Field(default=0, ge=0, le=10_000_000_000, description="Documents per collection to have before the measured run.")
    size_mb: float = Field(default=0, ge=0, le=10_000_000, description="Alternative to documents: approximate data size per collection.")
    batch_size: int = Field(default=1000, ge=1, le=100_000)


class DatasetSpec(Strict):
    database: str = "ballast_bench"
    collections: int = Field(default=1, ge=1, le=256)
    collection_prefix: str = "bench"
    indexes: list[IndexSpec] = Field(default_factory=list)
    load: DataLoad = Field(default_factory=DataLoad)

    @field_validator("database")
    @classmethod
    def _db(cls, value: str) -> str:
        if not DB_NAME_RE.match(value) or value in SYSTEM_DATABASES:
            raise ValueError("database must be 1-63 letters, digits, '_' or '-', and not admin, local or config")
        return value

    @field_validator("collection_prefix")
    @classmethod
    def _prefix(cls, value: str) -> str:
        if not COLL_PREFIX_RE.match(value):
            raise ValueError("collection_prefix must start with a letter and use letters, digits or '_'")
        return value

    def collection_names(self) -> list[str]:
        return [f"{self.collection_prefix}_{i + 1}" for i in range(self.collections)]


ReadMode = Literal["primary", "primaryPreferred", "secondary", "secondaryPreferred", "nearest"]
ATLAS_NODE_TYPES = ("ELECTABLE", "READ_ONLY", "ANALYTICS")


def _check_tags(mode: str | None, tags: list[dict[str, str]] | None) -> None:
    if tags and mode in (None, "primary"):
        raise ValueError("tag sets need a read preference other than primary, for example secondary")
    for tag_set in tags or []:
        for key, value in tag_set.items():
            if not key or ":" in key or "," in key or ":" in value or "," in value:
                raise ValueError(f"tag {key!r}: {value!r} may not be empty or contain ':' or ','")


def tag_strings(tags: list[dict[str, str]]) -> list[str]:
    """Tag sets as PyMongo's readPreferenceTags option strings; an empty set means any member."""
    return [",".join(f"{k}:{v}" for k, v in tag_set.items()) for tag_set in tags]


class ReadRoute(Strict):
    """Where one kind of read goes. Tag sets are tried in order; an empty set matches any eligible member."""

    mode: ReadMode = "secondary"
    tags: list[dict[str, str]] = Field(default_factory=list, max_length=10)
    max_staleness_seconds: int | None = Field(default=None, ge=90)
    label: str = Field(default="", max_length=40, description="Name used for this route's read gap; defaults to the nodeType tag.")

    @model_validator(mode="after")
    def _valid(self) -> ReadRoute:
        _check_tags(self.mode, self.tags)
        return self

    def name(self) -> str:
        if self.label:
            return self.label
        types = [t["nodeType"] for t in self.tags if t.get("nodeType")]
        return types[0] if types else self.mode


class WriteConcern(Strict):
    w: int | Literal["majority"] = "majority"
    j: bool | None = None
    wtimeout_ms: int | None = Field(default=None, ge=0)


class DriverSettings(Strict):
    write_concern: WriteConcern = Field(default_factory=WriteConcern)
    read_concern: Literal["local", "available", "majority", "linearizable", "snapshot"] | None = None
    read_preference: ReadMode | None = Field(
        default=None, description="Empty uses the connection string's readPreference (and readPreferenceTags), else primary."
    )
    read_preference_tags: list[dict[str, str]] | None = Field(default=None, max_length=10)
    max_staleness_seconds: int | None = Field(default=None, ge=90)
    track_members: bool = Field(default=True, description="Count operations and service time per member (command monitoring).")
    retry_writes: bool = True
    retry_reads: bool = True
    max_pool_size: int = Field(default=100, ge=1, le=10_000)
    min_pool_size: int = Field(default=0, ge=0, le=10_000)
    server_selection_timeout_ms: int = Field(default=30_000, ge=100)
    connect_timeout_ms: int = Field(default=10_000, ge=100)
    socket_timeout_ms: int = Field(default=0, ge=0)
    operation_timeout_ms: int | None = Field(default=None, ge=1, description="Client-side operation timeout (timeoutMS).")
    heartbeat_frequency_ms: int = Field(default=10_000, ge=500)

    @model_validator(mode="after")
    def _pools(self) -> DriverSettings:
        if self.min_pool_size > self.max_pool_size:
            raise ValueError("min_pool_size must be <= max_pool_size")
        _check_tags(self.read_preference, self.read_preference_tags)
        return self

    def client_options(self) -> dict:
        wc = self.write_concern
        options: dict = {
            "w": wc.w,
            "retryWrites": self.retry_writes,
            "retryReads": self.retry_reads,
            "maxPoolSize": self.max_pool_size,
            "minPoolSize": self.min_pool_size,
            "serverSelectionTimeoutMS": self.server_selection_timeout_ms,
            "connectTimeoutMS": self.connect_timeout_ms,
            "heartbeatFrequencyMS": self.heartbeat_frequency_ms,
        }
        if wc.j is not None:
            options["journal"] = wc.j
        if wc.wtimeout_ms is not None:
            options["wTimeoutMS"] = wc.wtimeout_ms
        if self.read_concern:
            options["readConcernLevel"] = self.read_concern
        if self.read_preference is not None:
            options["readPreference"] = self.read_preference
            if self.read_preference_tags:
                options["readPreferenceTags"] = tag_strings(self.read_preference_tags)
        if self.max_staleness_seconds is not None:
            options["maxStalenessSeconds"] = self.max_staleness_seconds
        if self.socket_timeout_ms:
            options["socketTimeoutMS"] = self.socket_timeout_ms
        if self.operation_timeout_ms is not None:
            options["timeoutMS"] = self.operation_timeout_ms
        return options


class LoadSpec(Strict):
    model: Literal["open", "closed"] = "open"
    rate: float = Field(default=1000, gt=0, le=10_000_000, description="Open model: operations per second.")
    concurrency: int = Field(default=64, ge=1, le=100_000, description="Closed model: workers. Open model: maximum operations in flight.")
    think_time_ms: int = Field(default=0, ge=0, le=600_000, description="Closed model: pause between a worker's operations.")
    processes: int = Field(default=1, ge=1, le=64, description="Generator processes. Rate and concurrency are split evenly.")


class RampStep(Strict):
    level: float = Field(gt=0, description="Rate (open model) or workers (closed model) for this step.")
    seconds: int = Field(ge=1, le=86_400 * 7)


class ScheduleSpec(Strict):
    warmup_seconds: int = Field(default=30, ge=0, le=86_400)
    ramp: list[RampStep] = Field(default_factory=list)
    steady_seconds: int | None = Field(default=300, ge=1, le=86_400 * 30, description="None runs until stopped.")
    drain_timeout_seconds: int = Field(default=15, ge=1, le=600)


class RetrySpec(Strict):
    max_attempts: int = Field(
        default=1, ge=1, le=20, description="Application-level attempts on top of driver retries. 1 means no extra retries."
    )
    initial_backoff_ms: int = Field(default=50, ge=0, le=60_000)
    max_backoff_ms: int = Field(default=2_000, ge=0, le=600_000)
    backoff_multiplier: float = Field(default=2.0, ge=1.0, le=10.0)


class SamplingSpec(Strict):
    enabled: bool = True
    interval_seconds: int = Field(default=5, ge=1, le=3600)


class AnalysisOverrides(Strict):
    baseline_seconds: int | None = Field(default=None, ge=5, le=3600)
    sustain_seconds: int | None = Field(default=None, ge=1, le=600)
    throughput_tolerance: float | None = Field(default=None, gt=0, lt=1)
    latency_tolerance: float | None = Field(default=None, gt=0, le=100)
    client_bound_rate_margin: float | None = Field(default=None, gt=0, lt=1)
    client_bound_cpu_percent: float | None = Field(default=None, gt=0, le=100)


class Guardrails(Strict):
    """Stop the run by itself when the cluster is clearly being hurt. Off unless a limit is set."""

    max_error_percent: float | None = Field(default=None, gt=0, le=100, description="Stop when this share of operations fail.")
    max_p99_ms: float | None = Field(default=None, gt=0, le=3_600_000, description="Stop when p99 response time is above this.")
    sustain_seconds: int = Field(default=10, ge=1, le=3600, description="For this many consecutive measured seconds.")

    def enabled(self) -> bool:
        return self.max_error_percent is not None or self.max_p99_ms is not None


class SLOSpec(Strict):
    """Pass/fail criteria for the whole measured run. Headless runs exit non-zero when one fails."""

    p50_ms: float | None = Field(default=None, gt=0)
    p99_ms: float | None = Field(default=None, gt=0)
    max_ms: float | None = Field(default=None, gt=0)
    error_percent: float | None = Field(default=None, ge=0, le=100)
    min_throughput: float | None = Field(default=None, gt=0, description="Successful operations per second.")
    min_throughput_ratio: float | None = Field(default=None, gt=0, le=1, description="Open model: achieved rate divided by the target.")

    def criteria(self) -> dict[str, float]:
        return {k: v for k, v in self.model_dump().items() if v is not None}


class Profile(Strict):
    name: str = "default"
    description: str = Field(default="", max_length=2000)
    operations: OperationMix = Field(default_factory=OperationMix)
    document: DocumentSpec = Field(default_factory=DocumentSpec)
    keys: KeySpec = Field(default_factory=KeySpec)
    dataset: DatasetSpec = Field(default_factory=DatasetSpec)
    driver: DriverSettings = Field(default_factory=DriverSettings)
    load: LoadSpec = Field(default_factory=LoadSpec)
    schedule: ScheduleSpec = Field(default_factory=ScheduleSpec)
    retry: RetrySpec = Field(default_factory=RetrySpec)
    sampling: SamplingSpec = Field(default_factory=SamplingSpec)
    analysis: AnalysisOverrides = Field(default_factory=AnalysisOverrides)
    read_routing: dict[Literal["find", "range", "aggregate", "analytics"], ReadRoute] = Field(
        default_factory=dict, description="Per-operation read preference, for example aggregations to analytics nodes."
    )
    guardrails: Guardrails = Field(default_factory=Guardrails)
    slo: SLOSpec = Field(default_factory=SLOSpec)
    seed: int = Field(default=42, ge=0, lt=2**32)

    @field_validator("name")
    @classmethod
    def _name(cls, value: str) -> str:
        value = value.strip()
        if not NAME_RE.match(value):
            raise ValueError("name must be 1-80 characters: letters, digits, space, '.', '_' or '-'")
        return value

    def target_level(self) -> float:
        return self.load.rate if self.load.model == "open" else float(self.load.concurrency)

    def plain_summary(self) -> str:
        mix = self.operations.normalized()
        parts = ", ".join(f"{round(v * 100)}% {k.replace('_', ' ')}" for k, v in sorted(mix.items(), key=lambda kv: -kv[1]))
        if self.load.model == "open":
            load = f"{self.load.rate:,.0f} operations per second (open model, up to {self.load.concurrency:,} in flight)"
        else:
            load = f"{self.load.concurrency:,} concurrent workers (closed model)"
        return f"{load}: {parts}; keys {self.keys.distribution}"
